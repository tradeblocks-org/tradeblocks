// Generate bounded snapshots for the resident, MCP package, and Node market tools
// from the library's single XNYS calendar authority.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import {
  enumerateXnysSessions,
  isEarlyCloseSession,
  isXnysSessionDate,
  XNYS_SESSION_CALENDAR_REVISION,
  XNYS_SESSION_CALENDAR_SUPPORTED_FROM,
  XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH,
} from "../packages/lib/calculations/xnys-session-calendar.ts";

const destination = process.argv[2];
if (!destination)
  throw new Error("Usage: node tools/generate-replay-calendar.mjs <resident-json-path>");
const early_close_dates = enumerateXnysSessions(
  XNYS_SESSION_CALENDAR_SUPPORTED_FROM,
  XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH,
).filter(isEarlyCloseSession);
const closedDates = [];
for (
  let cursor = new Date(`${XNYS_SESSION_CALENDAR_SUPPORTED_FROM}T00:00:00Z`);
  cursor.toISOString().slice(0, 10) <= XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH;
  cursor.setUTCDate(cursor.getUTCDate() + 1)
) {
  const weekday = cursor.getUTCDay();
  const iso = cursor.toISOString().slice(0, 10);
  if (weekday !== 0 && weekday !== 6 && !isXnysSessionDate(iso)) closedDates.push(iso);
}
const encoded = JSON.stringify(early_close_dates);
const sha256 = createHash("sha256").update(encoded).digest("hex");
const existing = existsSync(destination)
  ? JSON.parse(readFileSync(destination, "utf8"))
  : { revisions: {} };
const revisions =
  existing.revisions ??
  (existing.revision
    ? {
        [existing.revision]: {
          supported_from: existing.supported_from,
          supported_through: existing.supported_through,
          early_close_dates: existing.early_close_dates,
          sha256: existing.sha256,
        },
      }
    : {});
const revision = {
  supported_from: XNYS_SESSION_CALENDAR_SUPPORTED_FROM,
  supported_through: XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH,
  early_close_dates,
  sha256,
};
if (
  revisions[XNYS_SESSION_CALENDAR_REVISION] &&
  JSON.stringify(revisions[XNYS_SESSION_CALENDAR_REVISION]) !== JSON.stringify(revision)
) {
  throw new Error(`Existing replay calendar revision ${XNYS_SESSION_CALENDAR_REVISION} changed`);
}
revisions[XNYS_SESSION_CALENDAR_REVISION] = revision;
writeFileSync(destination, `${JSON.stringify({ revisions }, null, 2)}\n`);
writeFileSync(
  new URL("../packages/lib/calculations/xnys-early-close-dates.mjs", import.meta.url),
  `// Generated by tools/generate-replay-calendar.mjs from the bounded XNYS calendar.\n` +
    `export const calendarRevision = ${JSON.stringify(XNYS_SESSION_CALENDAR_REVISION)};\n` +
    `export const supportedFrom = ${JSON.stringify(XNYS_SESSION_CALENDAR_SUPPORTED_FROM)};\n` +
    `export const supportedThrough = ${JSON.stringify(XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH)};\n` +
    `export const earlyCloseDates = new Set(${encoded});\n`,
);
writeFileSync(
  new URL("../packages/mcp-server/src/market/provenance/xnys-calendar-data.ts", import.meta.url),
  `// Generated by tools/generate-replay-calendar.mjs from the bounded lib XNYS calendar.\n` +
    `export const XNYS_SESSION_CALENDAR_REVISION = ${JSON.stringify(XNYS_SESSION_CALENDAR_REVISION)} as const;\n` +
    `export const XNYS_SESSION_CALENDAR_SUPPORTED_FROM = ${JSON.stringify(XNYS_SESSION_CALENDAR_SUPPORTED_FROM)} as const;\n` +
    `export const XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH = ${JSON.stringify(XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH)} as const;\n` +
    `export const CLOSED_DATES: ReadonlySet<string> = new Set(${JSON.stringify(closedDates)});\n` +
    `export const EARLY_CLOSE_DATES: ReadonlySet<string> = new Set(${encoded});\n`,
);
