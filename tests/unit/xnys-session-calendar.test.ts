import {
  XNYS_SESSION_CALENDAR_REVISION,
  XNYS_SESSION_CALENDAR_SUPPORTED_FROM,
  XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH,
  XNYS_SESSION_CALENDAR_REVISION_V2,
  XNYS_SESSION_CALENDAR_SUPPORTED_FROM_V2,
  XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH_V2,
  isXnysSessionDate,
  enumerateXnysSessions,
  isEarlyCloseSession,
  isXnysSessionDateV2,
  enumerateXnysSessionsV2,
  isEarlyCloseSessionV2,
} from "@tradeblocks/lib";
import incumbent from "../fixtures/xnys-console-incumbent.json";

it("exports the historical calendar without changing provenance identity", () => {
  expect(XNYS_SESSION_CALENDAR_REVISION).toBe("xnys-full-day-2022-2030-v1");
  expect(XNYS_SESSION_CALENDAR_SUPPORTED_FROM).toBe("2022-01-01");
  expect(XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH).toBe("2030-12-31");
  expect(XNYS_SESSION_CALENDAR_REVISION_V2).toBe("xnys-full-day-2013-2030-v2");
  expect(XNYS_SESSION_CALENDAR_SUPPORTED_FROM_V2).toBe("2013-01-01");
  expect(XNYS_SESSION_CALENDAR_SUPPORTED_THROUGH_V2).toBe("2030-12-31");
  expect(enumerateXnysSessionsV2("2019-07-03", "2019-07-05")).toEqual(["2019-07-03", "2019-07-05"]);
});

it("matches the independently captured incumbent on every supported date and keeps v1 exact", () => {
  const sessions = new Set(incumbent.sessions);
  const early = new Set(incumbent.earlyCloses);
  expect(enumerateXnysSessionsV2("2013-01-01", "2030-12-31")).toEqual(incumbent.sessions);
  expect(enumerateXnysSessions("2022-01-01", "2030-12-31")).toEqual(
    incumbent.sessions.filter((d) => d >= "2022-01-01"),
  );
  for (let t = Date.UTC(2013, 0, 1); t < Date.UTC(2031, 0, 1); t += 86400000) {
    const date = new Date(t).toISOString().slice(0, 10);
    expect([date, isXnysSessionDateV2(date), isEarlyCloseSessionV2(date)]).toEqual([
      date,
      sessions.has(date),
      early.has(date),
    ]);
    if (date >= "2022-01-01") {
      expect([date, isXnysSessionDate(date), isEarlyCloseSession(date)]).toEqual([
        date,
        sessions.has(date),
        early.has(date),
      ]);
    }
  }
});

// Independently published NYSE schedules (not generated by either calendar).
// 2013: https://www.marketscreener.com/quote/stock/NYSE-EURONEXT-13866/news/NYSE-EURO-NYSE-Euronext-NYX-Announces-its-2012-and-2013-Holiday-Calendar-and-Early-Closings-for-13533281/
// The 2011 release lists only November's early close. Updated NYSE July/Christmas
// calendar footnotes are reproduced at (dated 2012-10-30):
// https://beforeitsnews.com/economy/2012/10/new-york-stock-exchange-nyse-holiday-calendar-2012-2013-2014-2459680.html
// 2014–15: https://ir.theice.com/press/news-details/2013/NYSE-Euronext-Announces-2015-Holiday-Calendar-and-Early-Closings/default.aspx
// 2016: https://ir.theice.com/press/news-details/2014/NYSE-Group-2016-Holiday-Calendar-and-Early-Closings/default.aspx
// 2017: https://ir.theice.com/press/news-details/2016/NYSE-Group-Announces-2017-Holiday-and-Early-Closings-Calendar/default.aspx
// 2018: https://ir.theice.com/press/news-details/2016/NYSE-Group-announces-2018-and-2019-holiday-and-early-closings-calendar/default.aspx
// Mourning: https://ir.theice.com/press/news-details/2018/New-York-Stock-Exchange-to-Honor-President-George-H-W-Bush/default.aspx
// 2019–21: https://ir.theice.com/press/news-details/2018/NYSE-Group-Announces-2019-2020-and-2021-Holiday-and-Early-Closings-Calendar/default.aspx
it.each([
  [2013, "01-01 01-21 02-18 03-29 05-27 07-04 09-02 11-28 12-25", "07-03 11-29 12-24"],
  [2014, "01-01 01-20 02-17 04-18 05-26 07-04 09-01 11-27 12-25", "07-03 11-28 12-24"],
  [2015, "01-01 01-19 02-16 04-03 05-25 07-03 09-07 11-26 12-25", "11-27 12-24"],
  [2016, "01-01 01-18 02-15 03-25 05-30 07-04 09-05 11-24 12-26", "11-25"],
  [2017, "01-02 01-16 02-20 04-14 05-29 07-04 09-04 11-23 12-25", "07-03 11-24"],
  [2018, "01-01 01-15 02-19 03-30 05-28 07-04 09-03 11-22 12-05 12-25", "07-03 11-23 12-24"],
  [2019, "01-01 01-21 02-18 04-19 05-27 07-04 09-02 11-28 12-25", "07-03 11-29 12-24"],
  [2020, "01-01 01-20 02-17 04-10 05-25 07-03 09-07 11-26 12-25", "11-27 12-24"],
  [2021, "01-01 01-18 02-15 04-02 05-31 07-05 09-06 11-25 12-24", "11-26"],
])("matches the published %s holiday and early-close schedule", (year, holidays, early) => {
  const closed = (holidays as string).split(" ");
  const shortened = (early as string).split(" ");
  for (let t = Date.UTC(Number(year), 0, 1); t < Date.UTC(Number(year) + 1, 0, 1); t += 86400000) {
    const day = new Date(t);
    const date = day.toISOString().slice(0, 10);
    const session =
      day.getUTCDay() !== 0 && day.getUTCDay() !== 6 && !closed.includes(date.slice(5));
    expect([date, isXnysSessionDateV2(date), isEarlyCloseSessionV2(date)]).toEqual([
      date,
      session,
      shortened.includes(date.slice(5)),
    ]);
  }
});

it.each(["2012-12-31", "2031-01-01"])("names unsupported date %s, revision and bounds", (date) => {
  for (const read of [
    isXnysSessionDateV2,
    isEarlyCloseSessionV2,
    (d: string) => enumerateXnysSessionsV2(d, d),
  ]) {
    expect(() => read(date)).toThrow(RangeError);
    expect(() => read(date)).toThrow(
      `${JSON.stringify(date)} is outside XNYS calendar revision xnys-full-day-2013-2030-v2 [2013-01-01, 2030-12-31]`,
    );
  }
});

it("preserves the exact public v1 out-of-range refusal text", () => {
  const suffix =
    '"2021-12-31" is outside XNYS calendar revision xnys-full-day-2022-2030-v1 [2022-01-01, 2030-12-31]';
  for (const read of [isXnysSessionDate, isEarlyCloseSession]) {
    expect(() => read("2021-12-31")).toThrow(new RangeError(`XNYS session date ${suffix}`));
  }
  expect(() => enumerateXnysSessions("2021-12-31", "2022-01-03")).toThrow(
    new RangeError(`XNYS session range from ${suffix}`),
  );
  expect(() => enumerateXnysSessions("2022-01-03", "2031-01-01")).toThrow(
    new RangeError(
      'XNYS session range through "2031-01-01" is outside XNYS calendar revision xnys-full-day-2022-2030-v1 [2022-01-01, 2030-12-31]',
    ),
  );
});
